const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  cloudStatus: () => ipcRenderer.invoke('cloud:status'),
  cloudSignIn: () => ipcRenderer.invoke('cloud:signIn'),
  cloudCancelSignIn: () => ipcRenderer.invoke('cloud:cancelSignIn'),
  cloudSignOut: () => ipcRenderer.invoke('cloud:signOut'),
  cloudSync: () => ipcRenderer.invoke('cloud:sync'),
  cloudDelete: () => ipcRenderer.invoke('cloud:delete'),
  onCloudStatus: fn => ipcRenderer.on('cloud:status', (_e, s) => fn(s)),
  onDataChanged: fn => ipcRenderer.on('data:changed', () => fn()),
  load: () => ipcRenderer.invoke('data:load'),
  save: (name, value) => ipcRenderer.invoke('data:save', name, value),
  saveInvoice: (bytes, client, name, altName, previous) => ipcRenderer.invoke('pdf:saveToClient', bytes, client, name, altName, previous),
  openClientFolder: client => ipcRenderer.invoke('shell:clientFolder', client),
  loadLogo: name => ipcRenderer.invoke('logo:load', name),
  chooseLogo: kind => ipcRenderer.invoke('logo:choose', kind),
  removeLogo: kind => ipcRenderer.invoke('logo:remove', kind),
  open: p => ipcRenderer.invoke('shell:open', p),
  showInFolder: p => ipcRenderer.invoke('shell:show', p),
  openDataDir: () => ipcRenderer.invoke('shell:dataDir'),
  chooseDataDir: () => ipcRenderer.invoke('data:chooseDir'),
  backupStatus: sel => ipcRenderer.invoke('backup:status', sel),
  backupSharedDrives: () => ipcRenderer.invoke('backup:sharedDrives'),
  backupFolders: (sel, parts) => ipcRenderer.invoke('backup:folders', sel, parts),
  gdriveStatus: () => ipcRenderer.invoke('gdrive:status'),
  gdriveConnect: () => ipcRenderer.invoke('gdrive:connect'),
  gdriveCancel: () => ipcRenderer.invoke('gdrive:cancel'),
  gdriveDisconnect: () => ipcRenderer.invoke('gdrive:disconnect'),
  backupWrite: (bytes, name, chosen, client) => ipcRenderer.invoke('backup:write', bytes, name, chosen, client),
  chooseBackupDir: current => ipcRenderer.invoke('backup:chooseDir', current),
  openBackupDir: chosen => ipcRenderer.invoke('backup:open', chosen),
  openExternal: url => ipcRenderer.invoke('shell:external', url),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateProgress: fn => ipcRenderer.on('update:progress', (_e, pct) => fn(pct)),
  updateInfo: () => ipcRenderer.invoke('update:info'),
  openReleases: () => ipcRenderer.invoke('update:releases'),
  version: () => ipcRenderer.invoke('app:version'),
  dueReminders: () => ipcRenderer.invoke('reminders:due'),
  skipReminder: id => ipcRenderer.invoke('reminders:skip', id),
  onReminders: fn => ipcRenderer.on('reminders', (_e, due) => fn(due)),
  onReminderOpen: fn => ipcRenderer.on('reminder:open', (_e, id) => fn(id)),
  takeReminderOpen: () => ipcRenderer.invoke('reminders:takeOpen'),
  reminderOverview: () => ipcRenderer.invoke('reminders:overview'),
  reminderTask: () => ipcRenderer.invoke('reminders:task'),
  testNotification: () => ipcRenderer.invoke('reminders:test'),
});
